"""使用已有固定源发布包时，逐文件核对真正将被运行的生产类和资源。"""
import argparse
import hashlib
import json
from pathlib import Path
import zipfile


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('jar', type=Path)
    parser.add_argument('out', type=Path)
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[2]
    config = json.loads(Path(__file__).with_name('experiment.json').read_text())
    digest = hashlib.sha256(args.jar.read_bytes()).hexdigest()
    if digest != config['baseline_jar_sha256']:
        raise SystemExit('Baseline jar identity mismatch')
    differences = []
    classes = resources = 0
    with zipfile.ZipFile(args.jar) as jar:
        for name in jar.namelist():
            if name.endswith('/') or name == 'META-INF/MANIFEST.MF':
                continue
            if name.endswith('.class'):
                path = root/'build/classes/java/main'/name
                classes += 1
            else:
                path = root/'build/resources/main'/name
                resources += 1
            if not path.exists() or path.read_bytes() != jar.read(name):
                differences.append(name)
    result = {'status': 'pass' if not differences else 'fail', 'classes': classes,
              'resources': resources, 'differences': differences, 'jar_sha256': digest,
              'production_source_commit': config['baseline_source_commit'],
              'resources_origin': 'verified existing release; not regenerated by this experiment'}
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(json.dumps(result, indent=2)+'\n')
    print(json.dumps({k: v for k, v in result.items() if k != 'differences'}))
    if differences:
        raise SystemExit('Production runtime differs from release: '+str(differences[:10]))


if __name__ == '__main__':
    main()

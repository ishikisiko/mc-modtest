#!/usr/bin/env python3
"""Generate ten semantic architectural items, variants and a real MC courtyard."""
from __future__ import annotations
import argparse
import json
import math
from pathlib import Path
import sys
import tempfile

HERE=Path(__file__).resolve().parent;ROOT=HERE.parents[1]
sys.path.insert(0,str(ROOT/'tools'));sys.path.insert(0,str(ROOT))
from tools.reference_courtyard.assembly_shapes import geometry,merge,parts
from tools.reference_courtyard.assembly_scene import build_scene
from tools.reference_courtyard.materials import model_elements,png_texture
from buildgen.modset import load_modset
from buildgen.nbtread import read_gzipped_nbt,state_string
import json_to_nbt as nbt
import voxel_dump_to_structures as exports

ASSETS=ROOT/'src/main/resources/assets/myvillage';DATA=ROOT/'src/main/resources/data/myvillage'
JAVA=ROOT/'src/main/java/com/example/myvillage/courtyard';OUT=ROOT/'out/preview/reference-courtyard-mc'


def generated_blocks(config):
    lines=['package com.example.myvillage.courtyard;',
           '// Generated by tools/reference_courtyard/minecraft.py. Do not edit.',
           'import com.mojang.serialization.MapCodec;',
           'import net.minecraft.world.level.block.Block;',
           'import net.minecraft.world.level.block.state.BlockBehaviour;',
           'import net.minecraft.world.level.block.state.properties.IntegerProperty;',
           'public final class CourtyardBlocks {']
    for f in config['families']:
        name=f['class'];n=len(f['variants']);p=max(math.prod(v['size']) for v in f['variants'])
        lines += [f'  public static final class {name} extends CourtyardAssemblyBlock {{',
                  f'    public static final MapCodec<{name}> CODEC=simpleCodec({name}::new);',
                  f'    private static final IntegerProperty VARIANT=IntegerProperty.create("variant",0,{n-1});',
                  '    private static final IntegerProperty PART='+ (f'IntegerProperty.create("part",0,{p-1});' if p>1 else 'null;'),
                  f'    public {name}(BlockBehaviour.Properties properties){{super(properties);}}',
                  f'    @Override public String familyId(){{return "{f["id"]}";}}',
                  '    @Override public IntegerProperty variantProperty(){return VARIANT;}',
                  '    @Override public IntegerProperty partProperty(){return PART;}',
                  '    @Override protected MapCodec<? extends Block> codec(){return CODEC;}','  }']
    lines += ['  public static CourtyardAssemblyBlock create(String family,BlockBehaviour.Properties properties){','    return switch(family){']
    for f in config['families']:lines.append(f'      case "{f["id"]}" -> new {f["class"]}(properties);')
    lines+=['      default -> throw new IllegalArgumentException("Unknown courtyard family "+family);','    };','  }','  private CourtyardBlocks(){}','}']
    return '\n'.join(lines)+'\n'


def generate():
    config=json.loads((HERE/'assemblies.json').read_text());materials=json.loads((HERE/'minecraft.json').read_text())
    outputs={};catalog=[];langs={'zh_cn':{},'en_us':{}};max_boxes=0
    def j(path,data):outputs[path]=(json.dumps(data,ensure_ascii=False,separators=(',',':'))+'\n').encode()
    for f in config['families']:
        identity=f['id'];max_parts=max(math.prod(v['size']) for v in f['variants']);variants=[];states={};loot=[];overrides=[]
        for vi,v in enumerate(f['variants']):
            cells=geometry(v);split=parts(v,cells);part_specs=[]
            for pi,local in enumerate(split):
                solid=merge({p:'solid' for p in local});boxes=[[*b['from'],*b['to']] for b in solid];max_boxes=max(max_boxes,len(boxes))
                part_specs.append({'boxes':boxes,'full':len(local)==4096})
                visual={'parent':'minecraft:block/block','textures':{'particle':f'myvillage:block/courtyard/{v["material"]}',**{m:'myvillage:block/courtyard/'+m for m in sorted(set(local.values()))}},'elements':model_elements(merge(local))}
                j(ASSETS/f'models/block/courtyard/{identity}/{vi}_{pi}.json',visual)
            for pi in range(max_parts):
                for turn,facing in enumerate(['north','east','south','west']):
                    key=f'facing={facing},variant={vi}'+(f',part={pi}' if max_parts>1 else '')
                    states[key]={'model':f'myvillage:block/courtyard/{identity}/{vi}_{pi}' if pi<len(split) else 'myvillage:block/courtyard/empty','y':90*turn}
            variants.append({'key':v['key'],'size':v['size'],'parts':part_specs})
            # The inventory icon represents the entire assembly, not one cell.
            boxes=merge(cells);scale=1/max(v['size']);ox=(16-v['size'][0]*16*scale)/2;oz=(16-v['size'][2]*16*scale)/2
            for b in boxes:
                for endpoint in ['from','to']:
                    x,y,z=b[endpoint];b[endpoint]=[round(x*scale+ox,5),round(y*scale,5),round(z*scale+oz,5)]
            j(ASSETS/f'models/item/courtyard/{identity}_{vi}.json',{'parent':'minecraft:block/block','textures':{'particle':'myvillage:block/courtyard/'+v['material'],**{m:'myvillage:block/courtyard/'+m for m in sorted(set(cells.values()))}},'elements':model_elements(boxes),
                'display':{'gui':{'rotation':[30,225,0],'translation':[0,0,0],'scale':[.85,.85,.85]}}})
            overrides.append({'predicate':{'custom_model_data':vi+1},'model':f'myvillage:item/courtyard/{identity}_{vi}'})
            properties={'variant':str(vi),**({'part':'0'} if max_parts>1 else {})}
            loot.append({'rolls':1,'conditions':[{'condition':'minecraft:block_state_property','block':'myvillage:'+identity,'properties':properties},{'condition':'minecraft:survives_explosion'}],
                         'entries':[{'type':'minecraft:item','name':'myvillage:'+identity,'functions':[{'function':'minecraft:set_components','components':{'minecraft:block_state':{'variant':str(vi)},'minecraft:custom_model_data':vi+1}}]}]})
            for lang,key in [('zh_cn','zh'),('en_us','en')]:langs[lang][f'variant.myvillage.{identity}.{vi}']=v[key]
        j(ASSETS/f'blockstates/{identity}.json',{'variants':states})
        j(ASSETS/f'models/item/{identity}.json',{'parent':f'myvillage:item/courtyard/{identity}_0','overrides':overrides})
        j(DATA/f'loot_table/blocks/{identity}.json',{'type':'minecraft:block','pools':loot})
        catalog.append({k:f[k] for k in ['id','sound','strength']}|{'light':f.get('light',0),'variants':variants})
        for lang,key in [('zh_cn','zh'),('en_us','en')]:langs[lang]['block.myvillage.'+identity]=f[key]
    j(ASSETS/'models/block/courtyard/empty.json',{'textures':{'particle':'myvillage:block/courtyard/plaster'},'elements':[]})
    j(DATA/'courtyard/assemblies.json',{'format':1,'families':catalog})
    outputs[JAVA/'CourtyardBlocks.java']=generated_blocks(config).encode()
    for material,spec in materials['materials'].items():outputs[ASSETS/f'textures/block/courtyard/{material}.png']=png_texture(material,spec,materials)
    messages={
        'zh_cn':{'itemGroup.myvillage.courtyard':'月洞水院 · 建筑构件','tooltip.myvillage.courtyard.select':'Shift＋右键：选择款式','tooltip.myvillage.courtyard.size':'整体尺寸：%s × %s × %s 格','screen.myvillage.courtyard.title':'选择构件款式','screen.myvillage.courtyard.hint':'每次整体放置消耗 1 个物品'},
        'en_us':{'itemGroup.myvillage.courtyard':'Moon Gate Courtyard · Building Kit','tooltip.myvillage.courtyard.select':'Shift + Right-click: choose a variant','tooltip.myvillage.courtyard.size':'Whole size: %s × %s × %s blocks','screen.myvillage.courtyard.title':'Choose a Building Variant','screen.myvillage.courtyard.hint':'Each complete placement consumes one item'}}
    for lang,entries in langs.items():
        path=ASSETS/f'lang/{lang}.json';old=json.loads(path.read_text());old={k:v for k,v in old.items() if not k.startswith(('block.myvillage.courtyard_','variant.myvillage.courtyard_','tooltip.myvillage.courtyard.','screen.myvillage.courtyard.'))}
        old.update(entries);old.update(messages[lang]);outputs[path]=(json.dumps(old,ensure_ascii=False,indent=2)+'\n').encode()
    for tool,sounds in [('axe',{'wood'}),('pickaxe',{'stone','metal'})]:j(DATA/f'tags/block/courtyard_{tool}.json',{'replace':False,'values':['myvillage:'+f['id'] for f in catalog if f['sound'] in sounds]})
    site=build_scene(config);blocks=dict(site.blocks)
    W,H,L=config['size']
    for x in range(W):
        for y in range(H):
            for z in range(L):blocks.setdefault((x,y,z),'minecraft:air')
    assert not load_modset('vanilla').palette_block_errors(list(set(blocks.values())))
    structure=exports.Structure(blocks)
    with tempfile.TemporaryDirectory() as temp:
        path=Path(temp)/'courtyard.nbt';nbt.write_gzipped_nbt(exports.build_structure_nbt(structure,exports.DEFAULT_DATA_VERSION,'MyVillage semantic courtyard'),str(path))
        outputs[DATA/f'structure/{config["template"]}.nbt']=path.read_bytes();outputs[OUT/'reference_courtyard.nbt']=path.read_bytes()
        _,root=read_gzipped_nbt(str(path));palette=[state_string(p) for p in root['palette']]
        restored={tuple(b['pos']):palette[b['state']] for b in root['blocks']}
        assert len(restored)==len(blocks)
        for pos,state in blocks.items():
            a,ap=nbt.parse_block_state(state);b,bp=nbt.parse_block_state(restored[pos])
            assert a==b and dict(ap)==dict(bp),pos
        sp=Path(temp)/'courtyard.schem';schem,_=exports.build_schem(structure,exports.DEFAULT_DATA_VERSION);exports.write_gzipped_nbt_ext(schem,sp,'Schematic');outputs[OUT/'reference_courtyard.schem']=sp.read_bytes()
    d={'id':'myvillage:'+config['template'],'size':config['size'],'fill_air':True,'blocks':[{'pos':list(p),'state':state} for p,state in blocks.items() if state!='minecraft:air'],
       'site':{'world_min':config['origin']},'presentation':{'role':'courtyard','name':'月洞水院 · 整体构件样板'}}
    j(OUT/'reference_courtyard.structure.json',d)
    runtime={'template':d['id'],'size':config['size'],'origin':config['origin'],'family_count':len(catalog),'variant_count':sum(len(f['variants']) for f in catalog),
             'whole_assemblies':site.assemblies,'fixture_cells':[[*p,state] for p,state in blocks.items() if state!='minecraft:air'],
             'viewpoints':{'roof-front':{'pos':[35.5,14,5],'target':[35.5,14,29]},'roof-side':{'pos':[60,13,16],'target':[34,13,30]},'roof-detail':{'pos':[45,12,12],'target':[37,12,19]},'overview':{'pos':[-2,24,-10],'target':[25,8,24]},'reference':{'pos':[16,9,-1],'target':[29,9,23]},'gate':{'pos':[10.5,4.5,13],'target':[10.5,5,21]},'gate-back':{'pos':[10.5,4.2,24.2],'target':[10.5,5,20.5]},'gate-oblique':{'pos':[5.5,4.8,16.5],'target':[9.5,5,20.5]},'gate-back-oblique':{'pos':[6,4.8,23.7],'target':[9.5,5,20.5]},'corridor':{'pos':[21.3,3.1,28.5],'target':[6,5,28.5]},'corridor-reverse':{'pos':[4.7,3.1,28.5],'target':[20,5,28.5]},'window-front':{'pos':[10,5,21.7],'target':[9.5,5.5,25.5]},'window-back':{'pos':[10,4.7,28],'target':[9.5,5.5,25.5]},'window-oblique':{'pos':[14,4.8,29],'target':[16.5,5.5,25.5]},'alcove':{'pos':[16,3.1,30],'target':[14,5,37]}}}
    j(OUT/'build-manifest.json',runtime)
    report={'item_entries':len(catalog),'variants':runtime['variant_count'],'model_parts':sum(len(v['parts']) for f in catalog for v in f['variants']),
            'max_collision_boxes':max_boxes,'whole_assemblies':len(site.assemblies),'placed_cells':sum(s!='minecraft:air' for s in blocks.values()),'template_roundtrip':True}
    j(OUT/'generation-check.json',report)
    return outputs,report,catalog,site


def main():
    ap=argparse.ArgumentParser();ap.add_argument('--check',action='store_true');args=ap.parse_args()
    outputs,report,_,_=generate();stale=[]
    for path,data in outputs.items():
        if args.check and not path.is_relative_to(ROOT/'out'):
            if not path.exists() or path.read_bytes()!=data:stale.append(str(path.relative_to(ROOT)))
        else:path.parent.mkdir(parents=True,exist_ok=True);path.write_bytes(data)
    if stale:raise SystemExit('Stale courtyard resources: '+', '.join(stale[:15]))
    print(json.dumps(report,ensure_ascii=False,indent=2))


if __name__=='__main__':main()

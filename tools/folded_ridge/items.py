"""生成折山岭妖兽的两枚材料图标和物品模型。"""
import argparse
from pathlib import Path

from ..gen_qingfeng_sword_model import encode_png

ASSETS = Path(__file__).resolve().parents[2] / 'src/main/resources/assets/yuanxian'
ART = {
    'moss_lantern_wick': (
        '''
        ................
        ........l.......
        .......lyl......
        ......lyyl......
        .....gyywlg.....
        ....gglwwgg.....
        ...bgglylsg.....
        ...bbsglgsb.....
        ....bgsssgb.....
        .....bgsgb......
        ....bbsgb.......
        ...bsb.bb.......
        ...bb...........
        ....b...........
        ................
        ................
        ''',
        {'b': '453c28', 's': '68603d', 'g': '778952', 'l': 'adbf72', 'y': 'ebd276', 'w': 'f9edad'},
    ),
    'layered_rock_fin': (
        '''
        ................
        ............s...
        ...........sm...
        .........ssmg...
        ........smgfg...
        ......ssmgfdg...
        ....ssfgmgsdg...
        ...sgmgmdmgd....
        ..sgdmfggdgs....
        ..gmfgddmggd....
        .sgfggmggds.....
        .gdmggdds.......
        .mgdsds.........
        ..dds...........
        ................
        ................
        ''',
        {'d': '303e43', 's': '455359', 'g': '637477', 'm': '879499', 'f': 'ae956a'},
    ),
}


def outputs():
    for name, (grid, palette) in ART.items():
        colors = {key: (*bytes.fromhex(value), 255) for key, value in palette.items()}
        colors['.'] = (0, 0, 0, 0)
        rows = grid.split()
        assert len(rows) == 16 and all(len(row) == 16 for row in rows)
        yield ASSETS/f'textures/item/{name}.png', encode_png([[colors[c] for c in row] for row in rows])
        yield ASSETS/f'models/item/{name}.json', (
            '{\n  "parent": "minecraft:item/generated",\n'
            f'  "textures": {{ "layer0": "yuanxian:item/{name}" }}\n'
            '}\n'
        ).encode()
    for name in ('lantern_carrier', 'cliff_ray'):
        yield ASSETS/f'models/item/{name}_spawn_egg.json', b'{\n  "parent": "minecraft:item/template_spawn_egg"\n}\n'


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    options = parser.parse_args()
    for path, payload in outputs():
        if options.check:
            if not path.is_file() or path.read_bytes() != payload:
                raise SystemExit(f'折山岭物品资源需要重新生成 {path.name}')
        else:
            path.write_bytes(payload)


if __name__ == '__main__':
    main()

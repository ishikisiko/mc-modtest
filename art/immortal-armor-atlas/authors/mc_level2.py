from mc_common import material, spec, Builder


def _paint(m, *rectangles):
    """以大像素色块手绘 16×16 织纹；矩形边界为左闭右开。"""
    rows = [list('2' * 16) for _ in range(16)]
    for x0, y0, x1, y1, ink in rectangles:
        assert 0 <= x0 < x1 <= 16 and 0 <= y0 < y1 <= 16
        assert 0 <= ink <= 4
        for y in range(y0, y1):
            for x in range(x0, x1):
                rows[y][x] = str(ink)
    m['pixelArt']['rows'] = [''.join(row) for row in rows]
    return m


def _mirror(poly, sign):
    points = [(sign * x, y) for x, y in poly]
    return points if sign > 0 else points[::-1]


def _ingot_surface(b, body, top, edge, name):
    """保留公共低扁共形底，换成每款自己的锭面手绘硬边嵌纹。"""
    b.ingot(body, top, edge, name)
    pieces = b.s['ingot']['components']
    pieces[:] = [c for c in pieces if c['shape'] == 'ingot']
    b.items = pieces



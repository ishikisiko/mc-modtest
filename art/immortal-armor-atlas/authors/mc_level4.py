def _paint(mat, strokes):
    """在父级五色、16×16 像素材质上手绘有留白的粗笔纹样。"""
    rows = [list(row) for row in mat['pixelArt']['rows']]
    for x, y, ink in strokes:
        assert 0 <= y < 16 and 0 <= x <= 16 - len(ink)
        rows[y][x:x + len(ink)] = ink
    mat['pixelArt']['rows'] = [''.join(row) for row in rows]
    return mat


def _ingot_base(b, body, top, edge, name):
    # 保留共形低扁锭坯，三款另绘各自的整幅锭面，不沿用默认两横线。
    b.ingot(body, top, edge, name)
    b.s['ingot']['components'][:] = b.s['ingot']['components'][:1]
    b.items = b.s['ingot']['components']



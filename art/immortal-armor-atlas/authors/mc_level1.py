from mc_common import material, spec, Builder


def _pixels(mat, drawing):
    rows = drawing.strip().splitlines()
    assert len(rows) == 16 and all(len(row) == 16 for row in rows)
    assert set("".join(rows)) <= set("01234")
    mat["pixelArt"]["rows"] = rows
    return mat


def _trousers(b, mat, width=4.15, depth=4.3, bottom=4.5):
    b.box("trouser_waist", "legs", mat, [0, 12, 0], [8.25, 1.2, depth], "完整方裤腰")
    for sign in (-1, 1):
        b.box(f"trouser_{sign}", "legs", mat, [sign * 2, (12.5 + bottom) / 2, 0],
              [width, 12.5 - bottom, depth], "左方裤腿" if sign < 0 else "右方裤腿")


def _ingot(b, body, top, edge, name):
    b.ingot(body, top, edge, name)
    # 保留共同低扁锭坯，三款均重新绘制锭面，不继承默认两道横纹。
    del b.s["ingot"]["components"][1:]
    b.items = b.s["ingot"]["components"]



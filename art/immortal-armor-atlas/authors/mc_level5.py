from mc_common import Builder, material, spec


def _paint(m, rows):
    """Explicit, coarse pixel placement; no procedural noise or smooth ramps."""
    assert len(rows) == 16 and all(len(r) == 16 and set(r) <= set("01234") for r in rows)
    m["pixelArt"]["rows"] = list(rows)
    return m


def _ingot_start(b, body, top, edge, name):
    # Keep the shared low, flat ingot family; replace its stock marks entirely.
    b.ingot(body, top, edge, name)
    components = b.s["ingot"]["components"]
    components[:] = [c for c in components if c["id"] == "ingot_body"]
    b.items = components


def _top_path(b, id, mat, points, width=.25):
    """One continuous engraving on the XZ ingot top, in model pixels."""
    for i, (a, c) in enumerate(zip(points, points[1:])):
        dx, dz = abs(c[0] - a[0]), abs(c[1] - a[1])
        assert (dx == 0) != (dz == 0), (id, a, c)
        b.box(f"ingot_{id}_{i}", "ingot", mat,
              [(a[0] + c[0]) / 2, .57, (a[1] + c[1]) / 2],
              [dx + width, .10, dz + width], "锭面连续方折嵌纹")



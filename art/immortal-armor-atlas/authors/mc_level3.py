from mc_common import material, spec, Builder


def _paint(mat, rows):
    """覆盖一块有留白的手画像素织纹，不添加光滑表面或细线几何。"""
    assert len(rows) == 16 and all(len(row) == 16 for row in rows)
    assert set("".join(rows)) <= set("01234")
    mat["pixelArt"]["rows"] = rows
    return mat


def _ingot(b, body, top, edge, name, draw):
    """保留共形低扁胎锭，替换共用示意锻纹为本款完整硬边嵌纹。"""
    b.ingot(body, top, edge, name)
    pieces = b.s["ingot"]["components"]
    pieces[:] = [c for c in pieces if c["id"] == "ingot_body"]
    armor_items = b.items
    b.items = pieces
    try:
        draw(b)
    finally:
        b.items = armor_items



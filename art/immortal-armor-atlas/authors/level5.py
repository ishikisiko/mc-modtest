SHAPES={"loft","tube","ribbon","panel","torus","ellipsoid","gem","box","ingot"}
ROLES={"head","chest","legs","boots","aura","ingot"}


def validate(designs):
    """不依赖 core 的独立检查，不宣称渲染或人工审美验收。"""
    assert isinstance(designs,list) and len(designs)==3, "化神恰好三套"
    assert len({s["id"] for s in designs})==3, "套装 id 唯一"

    def finite(value, where):
        if isinstance(value,(float,int)):
            assert not isinstance(value,bool) and math.isfinite(value), f"{where}: 非有限数字"
        elif isinstance(value,list):
            for i,v in enumerate(value): finite(v,f"{where}[{i}]")
        elif isinstance(value,dict):
            for k,v in value.items():
                if not isinstance(v,bool): finite(v,f"{where}.{k}")

    def proper_intersection(a,b,c,d):
        def cross(p,q,r): return (q[0]-p[0])*(r[1]-p[1])-(q[1]-p[1])*(r[0]-p[0])
        return cross(a,b,c)*cross(a,b,d)<-1e-14 and cross(c,d,a)*cross(c,d,b)<-1e-14

    summaries=[]
    for spec in designs:
        finite(spec,spec["id"])
        assert spec["level"]==5 and spec["realm"]=="化神"
        assert len(spec["materials"])>=5
        for key,mat in spec["materials"].items():
            assert re.fullmatch(r"#[0-9a-fA-F]{6}",mat["color"]), key
            for field in ["metalness","roughness","opacity"]:
                if field in mat: assert 0<=mat[field]<=1, (key,field)
            if "emissive" in mat: assert re.fullmatch(r"#[0-9a-fA-F]{6}",mat["emissive"])
            assert mat.get("emissiveIntensity",0)>=0
        all_components=spec["components"]+spec["ingot"]["components"]
        ids=[c["id"] for c in all_components]
        assert len(ids)==len(set(ids)), "组件 id 重复"
        assert 35<=len(spec["components"])<=120
        assert {"head","chest","legs","boots"}<=set(c["role"] for c in spec["components"])
        assert set(spec["parts"])=={"head","chest","legs","boots"}
        story="".join(str(spec[k]) for k in ["description","silhouette","materialStory","progression","segmentation","parts","ingot"])
        hanzi=len(re.findall(r"[\u4e00-\u9fff]",story))
        assert hanzi>=500, (spec["id"],hanzi)
        assert all(c["role"]=="ingot" for c in spec["ingot"]["components"])
        assert not any(c["role"]=="ingot" for c in spec["components"])
        for c in all_components:
            at=f'{spec["id"]}/{c["id"]}'
            assert c["shape"] in SHAPES and c["role"] in ROLES,at
            assert c["material"] in spec["materials"],at
            for field in ["topMaterial","edgeMaterial","trimMaterial"]:
                if field in c: assert c[field] in spec["materials"],(at,field)
            for field in ["position","rotation","scale","normal"]:
                if field in c: assert len(c[field])==3,(at,field)
            if "scale" in c: assert all(x>0 for x in c["scale"]),at
            if "normal" in c: assert sum(x*x for x in c["normal"])>0,at
            shape=c["shape"]
            if shape=="loft":
                assert len(c["rings"])>=2 and c["thickness"]>0,at
                assert all(r["rx"]>0 and r["rz"]>0 for r in c["rings"]),at
                assert all(a["y"]<b["y"] for a,b in zip(c["rings"],c["rings"][1:])),at
                assert 0<c.get("endAngle",360)-c.get("startAngle",0)<=360,at
            elif shape in {"tube","ribbon"}:
                assert len(c["path"])>=2 and all(len(p)==3 for p in c["path"]),at
                assert all(sum((x-y)**2 for x,y in zip(p,q))>1e-12 for p,q in zip(c["path"],c["path"][1:])),at
                size="radius" if shape=="tube" else "width"
                plural="radii" if shape=="tube" else "widths"
                assert c.get(size,1)>0,at
                if plural in c: assert len(c[plural])==len(c["path"]) and all(v>0 for v in c[plural]),at
                if shape=="ribbon": assert c["thickness"]>0,at
            elif shape=="panel":
                p=c["polygon"]
                assert len(p)>=3 and all(len(v)==2 for v in p),at
                area=sum(p[i][0]*p[(i+1)%len(p)][1]-p[(i+1)%len(p)][0]*p[i][1] for i in range(len(p)))
                assert abs(area)>1e-8 and c["depth"]>0 and c["bevel"]>=0,at
                for i in range(len(p)):
                    for j in range(i+2,len(p)):
                        if i==0 and j==len(p)-1: continue
                        assert not proper_intersection(p[i],p[(i+1)%len(p)],p[j],p[(j+1)%len(p)]),(at,"自交")
            elif shape=="torus":
                assert c["radius"]>c["tube"]>0,at
            elif shape in {"gem","ellipsoid"}:
                assert len(c["radii"])==3 and all(v>0 for v in c["radii"]),at
            elif shape in {"box","ingot"}:
                assert len(c["size"])==3 and all(v>0 for v in c["size"]),at
                if shape=="ingot": assert c["size"][1]/c["size"][0]<=.25,at
        assert sum(c["shape"]=="ingot" for c in spec["ingot"]["components"])==1
        # 包覆的独立结构证据：四个部位都有 loft，双腿、双靴、双袖实壳均存在。
        for role in ["head","chest","legs","boots"]:
            assert any(c["role"]==role and c["shape"]=="loft" for c in spec["components"]),(spec["id"],role)
        assert sum(c["role"]=="boots" and c["shape"]=="loft" for c in spec["components"])>=4
        assert not any(c["shape"]=="box" for c in spec["components"])
        # 有限数据和总体样本范围；精确曲面范围交给真实引擎构建后检查。
        summaries.append(dict(id=spec["id"],name=spec["name"],armorComponents=len(spec["components"]),
                              ingotComponents=len(spec["ingot"]["components"]),
                              roles=dict(Counter(c["role"] for c in spec["components"])),
                              shapes=dict(Counter(c["shape"] for c in spec["components"])),
                              materials=len(spec["materials"]),hanzi=hanzi,
                              ingotHeightWidth=next(c["size"][1]/c["size"][0] for c in spec["ingot"]["components"] if c["shape"]=="ingot")))
    assert len({json.dumps(s["components"],sort_keys=True) for s in designs})==3
    return summaries



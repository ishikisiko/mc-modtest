def material(name, color, metalness, roughness, **extra):
    return dict(name=name, color=color, metalness=metalness, roughness=roughness, **extra)


class Author:
    def __init__(self, spec):
        self.spec = spec
        self.items = spec["components"]

    def add(self, cid, name, role, mat, shape, **kwargs):
        c = dict(id=cid, name=name, role=role, material=mat, shape=shape, **kwargs)
        self.items.append(c)
        return c

    def loft(self, cid, name, role, mat, rows, **kwargs):
        rings = []
        for row in rows:
            y, rx, rz, *rest = row
            ring = dict(y=y, rx=rx, rz=rz)
            if rest:
                ring["cx"] = rest[0]
            if len(rest) > 1:
                ring["cz"] = rest[1]
            if len(rest) > 2:
                ring["wave"] = rest[2]
            rings.append(ring)
        return self.add(cid, name, role, mat, "loft", rings=rings, segments=48,
                        thickness=kwargs.pop("thickness", .005), **kwargs)

    def tube(self, cid, name, role, mat, path, radius=.003, **kwargs):
        return self.add(cid, name, role, mat, "tube", path=path, radius=radius,
                        steps=kwargs.pop("steps", 48), radialSegments=10, **kwargs)

    def ribbon(self, cid, name, role, mat, path, width, **kwargs):
        params = {"widths" if isinstance(width, list) else "width": width}
        return self.add(cid, name, role, mat, "ribbon", path=path,
                        normal=kwargs.pop("normal", [0, 0, 1]),
                        thickness=kwargs.pop("thickness", .004), steps=48, **params, **kwargs)

    def panel(self, cid, name, role, mat, polygon, **kwargs):
        return self.add(cid, name, role, mat, "panel", polygon=polygon,
                        depth=kwargs.pop("depth", .012), bevel=kwargs.pop("bevel", .003), **kwargs)


def arc_xz(rx, rz, y, start=0, end=360, cx=0, cz=0, n=32):
    return [[cx + rx * math.cos(math.radians(start + (end-start)*i/n)), y,
             cz + rz * math.sin(math.radians(start + (end-start)*i/n))] for i in range(n+1)]


def circle_xy(r, cy, z, n=48, cx=0):
    return [[cx+r*math.cos(2*math.pi*i/n), cy+r*math.sin(2*math.pi*i/n), z] for i in range(n+1)]


def mirrored(path, side):
    return [[side*x, y, z] for x, y, z in path]


